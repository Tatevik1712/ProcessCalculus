import hashlib
import itertools

def brute_force_chunk(args):
    """Выполняет перебор подмножества паролей в отдельном процессе.

    Функция фиксирует начальный символ (префикс) и генерирует все возможные
    комбинации оставшихся символов. Это позволяет изолировать вычисления
    в рамках одного процессорного ядра без пересечения с другими потоками.

    Args:
        args (tuple): Кортеж, содержащий четыре элемента:
            - prefix (str): Фиксированный начальный символ (или символы) пароля.
            - target_hash (str): Строка хэша, с которой идет сравнение.
            - total_length (int): Целевая длина полного пароля (7 символов).
            - alphabet (str): Строка со всеми доступными символами для перебора.

    Returns:
        str: Найденный пароль, если хэш совпал.
        None: Если в данном подмножестве совпадений не обнаружено.
    """
    # Распаковываем кортеж аргументов, переданных через пул процессов
    prefix, target_hash, total_length, alphabet = args

    # Вычисляем, сколько символов нужно сгенерировать "внутри" текущего процесса.
    # Например, если общая длина 7, а префикс занимает 1 символ, нужно добрать еще 6.
    remaining_length = total_length - len(prefix)

    # itertools.product генерирует декартово произведение алфавита сам на себя
    # n раз. Алгоритм реализован на C, что делает генерацию комбинаций
    # значительно быстрее, чем использование вложенных циклов for на Python.
    for suffix_tuple in itertools.product(alphabet, repeat=remaining_length):
        # Превращаем кортеж символов ('a', '1', ...) в единую строку и склеиваем с префиксом
        candidate = prefix + "".join(suffix_tuple)

        # Переводим строку в байты (UTF-8), так как hashlib работает только с байтовыми данными,
        # считаем SHA-512 хэш и переводим его в привычную шестнадцатеричную строку (hex-строку).
        candidate_hash = hashlib.sha512(candidate.encode("utf-8")).hexdigest()

        # Если сгенерированный хэш совпал с искомым — задача решена
        if candidate_hash == target_hash:
            return candidate  # Возвращаем строку-пароль и прерываем цикл текущего процесса

    return None  # Если цикл завершился и ничего не найдено, возвращаем пустой результат