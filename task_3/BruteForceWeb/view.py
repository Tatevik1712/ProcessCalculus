"""Модуль представления (View) для веб-брутфорса.

Отвечает исключительно за консольное отображение и форматирование вывода.
"""


class ConsoleView:
    """Интерфейс командной строки для вывода состояния брутфорса."""

    @staticmethod
    def show_banner(url, user, cores):
        """Выводит стартовую информацию о задаче."""
        print("=" * 60)
        print(" АТАКА МЕТОДОМ БРУТФОРСА ДЛЯ ВЕБ-ФОРМЫ (MVC Architecture)")
        print("=" * 60)
        print(f"[+] Целевой URL:   {url}")
        print(f"[+] Пользователь:  {user}")
        print(f"[+] Потоков (CPU): {cores}")
        print("[-] Запуск подбора... Пожалуйста, подождите.\n")

    @staticmethod
    def report_success(password, elapsed_time):
        """Информирует об успешном нахождении пароля."""
        print("\n" + "!" * 60)
        print(f"[ УСПЕХ ] Пароль успешно подобран: {password}")
        print(f"[ ИНФО  ] Затрачено времени: {elapsed_time:.2f} сек.")
        print("!" * 60)

    @staticmethod
    def report_failure():
        """Выводит сообщение, если перебор завершился безрезультатно."""
        print("\n" + "-" * 60)
        print("[-] Обход завершен. Пароль не найден во всем алфавите.")
        print("-" * 60)