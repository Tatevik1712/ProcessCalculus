import hashlib
import itertools
import multiprocessing
import sys
import time

ALPHABET = "0123456789abcdefghijklmnopqrstuvwxyz"
# длина пароля
PASSWORD_LENGTH = 7
# хэш SHA-512
TARGET_HASH = (
    "6e9564685eb16c0c516ff1210dc6e94dc183faf1a1026116fccddb4d215e8df8eb82"
    "440d2bbbf4ee5d605edef87db7ce602eeb0bf0b8000b063753b8996e2ae3"
)

def brute_force_chunk(args):
    """Выполняет перебор подмножества паролей в отдельном процессе.

    Функция фиксирует начальный символ (префикс) и генерирует все возможные
    комбинации оставшихся символов. Это позволяет изолировать вычисления
    в рамках одного процессорного ядра без пересечения с другими потоками.

    Args:
        args (tuple): Кортеж, содержащий четыре элемента:
            - prefix (str): Фиксированный начальный символ (или символы) пароля.
            - target_hash (str): Строка хэша, с которой идет сравнение.
            - total_length (int): Целевая длина полного пароля (7 символов).
            - alphabet (str): Строка со всеми доступными символами для перебора.

    Returns:
        str: Найденный пароль, если хэш совпал.
        None: Если в данном подмножестве совпадений не обнаружено.
    """
    # Распаковываем кортеж аргументов, переданных через пул процессов
    prefix, target_hash, total_length, alphabet = args

    # Вычисляем, сколько символов нужно сгенерировать "внутри" текущего процесса.
    # Например, если общая длина 7, а префикс занимает 1 символ, нужно добрать еще 6.
    remaining_length = total_length - len(prefix)

    # itertools.product генерирует декартово произведение алфавита сам на себя
    # n раз. Алгоритм реализован на C, что делает генерацию комбинаций
    # значительно быстрее, чем использование вложенных циклов for на Python.
    for suffix_tuple in itertools.product(alphabet, repeat=remaining_length):
        # Превращаем кортеж символов ('a', '1', ...) в единую строку и склеиваем с префиксом
        candidate = prefix + "".join(suffix_tuple)

        # Переводим строку в байты (UTF-8), так как hashlib работает только с байтовыми данными,
        # считаем SHA-512 хэш и переводим его в привычную шестнадцатеричную строку (hex-строку).
        candidate_hash = hashlib.sha512(candidate.encode("utf-8")).hexdigest()

        # Если сгенерированный хэш совпал с искомым — задача решена
        if candidate_hash == target_hash:
            return candidate  # Возвращаем строку-пароль и прерываем цикл текущего процесса

    return None  # Если цикл завершился и ничего не найдено, возвращаем пустой результат


def main():
    """Управляющая функция для инициализации и контроля процесса брутфорса.
    Определяет аппаратные возможности системы (кол-во ядер CPU), разбивает
    общую задачу перебора на независимые сегменты (задачи) по первому символу,
    инициирует пул параллельных процессов и динамически обрабатывает их результаты.
    """
    print(f"Целевой хэш: {TARGET_HASH}")
    print(f"Алфавит: {ALPHABET} (длина: {len(ALPHABET)})")
    print(f"Длина пароля: {PASSWORD_LENGTH}")

    # Автоматически определяем количество логических ядер CPU (включая Hyper-Threading).
    # На основе этого числа Python создаст оптимальное количество параллельных воркеров.
    num_cores = multiprocessing.cpu_count()
    print(f"Задействовано ядер процессора: {num_cores}")

    # Разделение пространства поиска (Chunking / Map-Reduce подход).
    # Создаем список задач (tasks). Каждая задача — это кортеж параметров для brute_force_chunk.
    # Так как в ALPHABET 36 символов, мы получаем ровно 36 уникальных задач.
    # Задача 1 начнется с '0', Задача 2 — с '1', ..., Задача 36 — с 'z'.
    tasks = [(char, TARGET_HASH, PASSWORD_LENGTH, ALPHABET) for char in ALPHABET]

    # Фиксируем время старта для последующего замера производительности
    start_time = time.time()

    # Создаем пул процессов. Контекстный менеджер 'with' гарантирует корректное
    # закрытие пула и освобождение системных ресурсов после завершения блока кода.
    with multiprocessing.Pool(processes=num_cores) as pool:
        # pool.imap_unordered лениво передает задачи из списка tasks свободным процессам.
        # В отличие от обычного map, он возвращает результат мгновенно, как только ХОТЬ ОДИН
        # процесс завершит работу (порядок завершения задач не важен). Это критично для брутфорса.
        for result in pool.imap_unordered(brute_force_chunk, tasks):
            # Если brute_force_chunk вернул строку (пароль), а не None:
            if result:
                end_time = time.time()
                print("\n" + "=" * 40)
                print(f"ПАРОЛЬ НАЙДЕН: {result}")
                print(f"Затраченное время: {end_time - start_time:.2f} сек.")
                print("=" * 40)

                # Поскольку нужный пароль уже найден, продолжать вычисления на других ядрах
                # нет смысла. Принудительно уничтожаем (terminate) все оставшиеся активные процессы в пуле.
                pool.terminate()
                # Немедленно завершаем работу всего скрипта с кодом 0 (успех)
                sys.exit(0)

    # Если пул обработал абсолютно все 36 задач и ни разу не сработал `if result:`
    print("\nПароль не найден во всем пространстве поиска.")


if __name__ == "__main__":
    # Данная конструкция обязательна для работы модуля multiprocessing.
    # Она защищает дочерние процессы от бесконечной рекурсивной загрузки главного модуля main
    # при импорте скрипта в подпроцессах (особенно актуально для платформ Windows и macOS).
    main()